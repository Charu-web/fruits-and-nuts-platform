export function getProductAndVariantById(variantId: string) {
  for (const product of STOREFRONT_PRODUCTS) {
    if (product.variants) {
      const v = product.variants.find((variant) => variant.id === variantId);
      if (v) {
        return { product, variant: v };
      }
    }
  }
  return null;
}

